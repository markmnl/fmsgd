// Command gen regenerates tables.go for package emoji from the Unicode emoji
// data files. Run from the repository root:
//
//	go run ./internal/emoji/gen [emoji-test.txt emoji-data.txt]
//
// Without arguments the latest files are downloaded from unicode.org.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	testURL = "https://www.unicode.org/Public/emoji/latest/emoji-test.txt"
	dataURL = "https://www.unicode.org/Public/UCD/latest/ucd/emoji/emoji-data.txt"
)

func open(arg, url string) (io.ReadCloser, error) {
	if arg != "" {
		return os.Open(arg)
	}
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		resp.Body.Close()
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return resp.Body, nil
}

type span struct{ lo, hi rune }

func main() {
	var testArg, dataArg string
	if len(os.Args) == 3 {
		testArg, dataArg = os.Args[1], os.Args[2]
	} else if len(os.Args) != 1 {
		fmt.Fprintln(os.Stderr, "usage: gen [emoji-test.txt emoji-data.txt]")
		os.Exit(2)
	}

	test, err := open(testArg, testURL)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer test.Close()
	rgi, version := parseTest(test)

	data, err := open(dataArg, dataURL)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer data.Close()
	props := parseData(data)

	var buf bytes.Buffer
	w := &buf

	fmt.Fprintf(w, "// Code generated by internal/emoji/gen from Unicode Emoji %s; DO NOT EDIT.\n\n", version)
	fmt.Fprintln(w, "package emoji")
	fmt.Fprintln(w)
	fmt.Fprintln(w, `import "unicode"`)
	fmt.Fprintln(w)
	fmt.Fprintf(w, "// Version is the Unicode Emoji version the tables were generated from.\nconst Version = %q\n\n", version)
	fmt.Fprintf(w, "// rgi is the RGI_Emoji set (UTS #51): every fully-qualified emoji sequence.\nvar rgi = map[string]struct{}{\n")
	for _, s := range rgi {
		fmt.Fprintf(w, "\t%q: {},\n", s)
	}
	fmt.Fprintln(w, "}")
	for _, name := range []string{"Emoji", "Emoji_Presentation", "Emoji_Modifier", "Emoji_Modifier_Base", "Emoji_Component"} {
		writeTable(w, name, props[name])
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "format generated source:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("internal/emoji/tables.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// parseTest returns the fully-qualified sequences and the file's version.
func parseTest(r io.Reader) ([]string, string) {
	var seqs []string
	version := "unknown"
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := sc.Text()
		if after, ok := strings.CutPrefix(line, "# Version:"); ok {
			version = strings.TrimSpace(after)
			continue
		}
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		// <code points> ; <status> # <emoji> E<ver> <name>
		semi := strings.IndexByte(line, ';')
		hash := strings.IndexByte(line, '#')
		if semi < 0 || hash < 0 {
			continue
		}
		status := strings.TrimSpace(line[semi+1 : hash])
		if status != "fully-qualified" {
			continue
		}
		var b strings.Builder
		for cp := range strings.FieldsSeq(line[:semi]) {
			n, err := strconv.ParseUint(cp, 16, 32)
			if err != nil {
				fmt.Fprintf(os.Stderr, "bad code point %q\n", cp)
				os.Exit(1)
			}
			b.WriteRune(rune(n))
		}
		seqs = append(seqs, b.String())
	}
	sort.Strings(seqs)
	return seqs, version
}

// parseData returns the code point spans of each emoji property.
func parseData(r io.Reader) map[string][]span {
	props := make(map[string][]span)
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := sc.Text()
		if hash := strings.IndexByte(line, '#'); hash >= 0 {
			line = line[:hash]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		parts := strings.Split(line, ";")
		if len(parts) != 2 {
			continue
		}
		rng, prop := strings.TrimSpace(parts[0]), strings.TrimSpace(parts[1])
		lo, hi := rng, rng
		if before, after, ok := strings.Cut(rng, ".."); ok {
			lo, hi = before, after
		}
		l, err1 := strconv.ParseUint(lo, 16, 32)
		h, err2 := strconv.ParseUint(hi, 16, 32)
		if err1 != nil || err2 != nil {
			fmt.Fprintf(os.Stderr, "bad range %q\n", rng)
			os.Exit(1)
		}
		props[prop] = append(props[prop], span{rune(l), rune(h)})
	}
	for name := range props {
		s := props[name]
		sort.Slice(s, func(i, j int) bool { return s[i].lo < s[j].lo })
		// merge adjacent spans
		merged := s[:0]
		for _, sp := range s {
			if n := len(merged); n > 0 && merged[n-1].hi+1 >= sp.lo {
				if sp.hi > merged[n-1].hi {
					merged[n-1].hi = sp.hi
				}
				continue
			}
			merged = append(merged, sp)
		}
		props[name] = merged
	}
	return props
}

func writeTable(w io.Writer, name string, spans []span) {
	goName := "prop" + strings.ReplaceAll(name, "_", "")
	fmt.Fprintf(w, "\n// %s is the %s property.\nvar %s = &unicode.RangeTable{\n", goName, name, goName)
	var r16, r32 []span
	for _, sp := range spans {
		if sp.hi < 0x10000 {
			r16 = append(r16, sp)
		} else if sp.lo >= 0x10000 {
			r32 = append(r32, sp)
		} else {
			r16 = append(r16, span{sp.lo, 0xFFFF})
			r32 = append(r32, span{0x10000, sp.hi})
		}
	}
	fmt.Fprintln(w, "\tR16: []unicode.Range16{")
	for _, sp := range r16 {
		fmt.Fprintf(w, "\t\t{0x%04X, 0x%04X, 1},\n", sp.lo, sp.hi)
	}
	fmt.Fprintln(w, "\t},")
	fmt.Fprintln(w, "\tR32: []unicode.Range32{")
	for _, sp := range r32 {
		fmt.Fprintf(w, "\t\t{0x%X, 0x%X, 1},\n", sp.lo, sp.hi)
	}
	fmt.Fprintln(w, "\t},")
	fmt.Fprintln(w, "}")
}
